#Requires -Version 7
<#
.SYNOPSIS
  One-time developer setup for circloo: GitHub login (used by the GitHub MCP server), git hooks, issue labels.
#>
$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { throw 'Install the GitHub CLI: https://cli.github.com' }
gh auth status *> $null
if ($LASTEXITCODE -ne 0) { gh auth login --hostname github.com --git-protocol https --web }

# "No issue, no development" commit hook.
git config core.hooksPath scripts/git-hooks
Write-Host 'Git hooks enabled (scripts/git-hooks).'

# Labels used by the issue workflow (see docs/workflow/issue-driven-development.md).
$labels = @(
  @('type:idea',    'c5def5', 'Raw idea - needs a Spec-Kit spec before any code'),
  @('type:feature', '0e8a16', 'Feature with an approved spec/plan'),
  @('type:task',    '1d76db', 'Task generated by /speckit-taskstoissues'),
  @('type:bug',     'd73a4a', 'Something is broken'),
  @('type:chore',   'cfd3d7', 'Tooling, infra, docs'),
  @('area:spaces',  'fbca04', 'Spaces, members, invitations'),
  @('area:mood',    'fbca04', 'Daily mood / motivation check-ins'),
  @('area:boards',  'fbca04', 'Shared real-time boards'),
  @('area:fun',     'fbca04', 'Icebreakers and jokes'),
  @('area:auth',    'fbca04', 'Email sign-in, invites, enterprise SSO'),
  @('area:i18n',    'fbca04', 'EN / FR / AR (RTL) / ES'),
  @('area:infra',   'fbca04', 'Azure IaC and deployment'),
  @('area:design',  'fbca04', 'UI/UX, Impeccable reviews')
)
foreach ($l in $labels) { gh label create $l[0] --color $l[1] --description $l[2] --force | Out-Null }
Write-Host "Labels synced."

Write-Host "`nDone. Start Claude in this folder and approve the 'github' MCP server and the 'impeccable' plugin when asked." -ForegroundColor Green
